CREATE TABLE cashback_wallet
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    BIGINT                                  NOT NULL,
    balance    DECIMAL(15, 2) DEFAULT 0.00             NOT NULL,
    version    BIGINT         DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_cashback_wallet PRIMARY KEY (id),
    CONSTRAINT uc_cashback_wallet_user UNIQUE (user_id)
);

ALTER TABLE cashback_wallet
    ADD CONSTRAINT fk_cashback_wallet_on_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

CREATE TABLE cashback_transaction
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    transaction_type      VARCHAR(31)                             NOT NULL,
    wallet_id             BIGINT                                  NOT NULL,
    description           VARCHAR(255)                            NOT NULL,
    value                 DECIMAL(15, 2)                          NOT NULL,
    date_time_transaction TIMESTAMP WITH TIME ZONE                NOT NULL,
    approved_at           TIMESTAMP WITH TIME ZONE,
    status                VARCHAR(255)                            NOT NULL,
    date_time_expiration  TIMESTAMP WITH TIME ZONE,
    collection_point_id   BIGINT,
    cashback_percentage   DECIMAL(5, 2),
    partner_store         VARCHAR(255),
    CONSTRAINT pk_cashback_transaction PRIMARY KEY (id)
);

ALTER TABLE cashback_transaction
    ADD CONSTRAINT fk_cashback_transaction_on_wallet
        FOREIGN KEY (wallet_id) REFERENCES cashback_wallet (id);

ALTER TABLE cashback_transaction
    ADD CONSTRAINT fk_cashback_transaction_on_collection_point
        FOREIGN KEY (collection_point_id) REFERENCES collection_points (id);

CREATE INDEX idx_trx_wallet_created
    ON cashback_transaction (wallet_id, date_time_transaction DESC);

ALTER TABLE disposals
    ADD COLUMN cashback_credit_id BIGINT;

ALTER TABLE disposals
    ADD CONSTRAINT fk_disposals_on_cashback_credit
        FOREIGN KEY (cashback_credit_id) REFERENCES cashback_transaction (id);